let rec maybe_hoist (g : Pulse_Typing_Env.env) (arg : (FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv)) : (FStarC_Tactics_Types.ref_proofstate -> (Pulse_Typing_Env.env * ((Pulse_Syntax_Base.binder * Prims.int * Pulse_Syntax_Base.st_term)) list * (FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv))) =
  (fun ps -> (match arg with
    | (t, q) -> (let x = (FStar_Reflection_V2_Collect.collect_app_ln t) in
      ((match x with
        | (head, args) -> (match args with
            | [] -> (fun ps1 -> (let x1 = (convert_fstar_match g t maybe_hoist ps1) in
              (match x1 with
                | (Some (st_cond)) -> (let x2 = (bind_st_term g st_cond ps1) in
                  (match x2 with
                    | (g1, b, x3, var_t) -> (g1, ((b, x3, st_cond) :: []), (var_t, q))
                  ))
                | None -> (g, [], arg)
              )))
            | tmp -> (fun ps1 -> (let x1 = (is_stateful_application g t ps1) in
              (match x1 with
                | None -> (let x2 = (maybe_hoist_args g args ps1) in
                  (match x2 with
                    | (g1, binders, args1) -> (match binders with
                        | [] -> (g1, [], arg)
                        | tmp1 -> (g1, binders, (let tmp2 = (FStarC_Reflection_V2_Builtins.range_of_term t) in
                          let tmp3 = (Pulse_RuntimeUtils.mk_app_flat head args1 tmp2) in
                          (tmp3, q)))
                      )
                  ))
                | (Some (tmp1)) -> (let x2 = (maybe_hoist_args g args ps1) in
                  ((match x2 with
                    | (g1, binders, args1) -> (if (match args1 with
                        | (hd :: tl) -> true
                        | tmp2 -> false
                      ) then (fun ps2 -> (let tmp2 = (FStarC_Reflection_V2_Builtins.range_of_term t) in
                      let tmp3 = (Pulse_RuntimeUtils.mk_app_flat head args1 tmp2) in
                      let x3 = (as_stateful_application tmp3 head args1) in
                      let x4 = (bind_st_term g1 x3 ps2) in
                      (match x4 with
                        | (g2, b, x5, t1) -> (g2, (FStar_List_Tot_Base.op_At binders ((b, x5, x3) :: [])), (t1, q))
                      ))) else (FStar_Tactics_V2_Derived.fail "Impossible: is_stateful_application returned true but no args to hoist"))
                  ) ps1))
              )))
          )
      ) ps))
  ))

and maybe_hoist_args (g : Pulse_Typing_Env.env) (args : ((FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv)) list) : (FStarC_Tactics_Types.ref_proofstate -> (Pulse_Typing_Env.env * ((Pulse_Syntax_Base.binder * Prims.int * Pulse_Syntax_Base.st_term)) list * ((FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv)) list)) =
  (FStar_Tactics_Util.fold_right (fun arg tmp -> (match tmp with
    | (g1, binders, args1) -> (fun ps -> (let x = (maybe_hoist g1 arg ps) in
      (match x with
        | (g2, binders', arg1) -> (g2, (FStar_List_Tot_Base.op_At binders' binders), (arg1 :: args1))
      )))
  )) args (g, [], []))

let maybe_hoist_top (hoist_top_level : bool) (g : Pulse_Typing_Env.env) (tt : (FStarC_Reflection_Types.term, Pulse_Syntax_Base.st_term) FStar_Pervasives.either) : (FStarC_Tactics_Types.ref_proofstate -> (Pulse_Typing_Env.env * ((Pulse_Syntax_Base.binder * Prims.int * Pulse_Syntax_Base.st_term)) list * (FStarC_Reflection_Types.term, Pulse_Syntax_Base.st_term) FStar_Pervasives.either)) =
  (if (not hoist_top_level) then (fun tmp -> (g, [], tt)) else (match tt with
    | (FStar_Pervasives.Inl (tmp)) -> (fun tmp1 -> (g, [], tt))
    | (FStar_Pervasives.Inr (st)) -> (fun ps -> (let x = (bind_st_term g st ps) in
      (match x with
        | (g1, b, x1, t) -> (g1, ((b, x1, st) :: []), (FStar_Pervasives.Inl (t)))
      )))
  ))

let hoist_stateful_apps (g : Pulse_Typing_Env.env) (tt : (FStarC_Reflection_Types.term, Pulse_Syntax_Base.st_term) FStar_Pervasives.either) (hoist_top_level : bool) (context : ((FStarC_Reflection_Types.term, Pulse_Syntax_Base.st_term) FStar_Pervasives.either -> (FStarC_Tactics_Types.ref_proofstate -> Pulse_Syntax_Base.st_term))) (ps : FStarC_Tactics_Types.ref_proofstate) : (Pulse_Syntax_Base.st_term) option =
  (let x = (decompose_app g tt ps) in
  (match x with
    | None -> None
    | (Some ((head, args, rebuild))) -> (let x1 = (maybe_hoist_args g args ps) in
      ((match x1 with
        | (tmp, binders, args1) -> (match args1 with
            | [] -> (match tt with
                | (FStar_Pervasives.Inl (t)) -> (fun ps1 -> (let x2 = (convert_fstar_match g t maybe_hoist ps1) in
                  (match x2 with
                    | (Some (st_cond)) -> (let x3 = (Pulse_RuntimeUtils.range_of_term t) in
                      let x4 = (bind_st_term g st_cond ps1) in
                      (match x4 with
                        | (tmp1, b, v, var_t) -> (let x5 = (context (FStar_Pervasives.Inl (var_t)) ps1) in
                          (Some ((Pulse_Syntax_Base.mk_term (Pulse_Syntax_Base.Tm_Bind (({ Pulse_Syntax_Base.binder = b;
                            head = st_cond;
                            body = (Pulse_Syntax_Naming.close_st_term x5 v) } : Pulse_Syntax_Base.st_term'__Tm_Bind__payload))) x3))))
                      ))
                    | None -> None
                  )))
                | tmp1 -> (fun tmp2 -> None)
              )
            | tmp1 -> (fun ps1 -> (let x2 = (rebuild args1 ps1) in
              let x3 = (maybe_hoist_top (hoist_top_level && (match tt with
                  | (FStar_Pervasives.Inl (v)) -> true
                  | tmp2 -> false
                )) g x2 ps1) in
              (match x3 with
                | (tmp2, binders', tt') -> (let x4 = (FStar_List_Tot_Base.op_At binders binders') in
                  (match x4 with
                    | [] -> (match (tt, tt') with
                        | ((FStar_Pervasives.Inl (tmp3)), (FStar_Pervasives.Inr (tmp4))) -> (let x5 = (context tt' ps1) in
                          (Some (x5)))
                        | tmp3 -> None
                      )
                    | tmp3 -> (let x5 = (context tt' ps1) in
                      (Some ((FStar_List_Tot_Base.fold_right (fun tmp4 body -> (match tmp4 with
                        | (b, v, arg) -> (Pulse_Syntax_Base.mk_term (Pulse_Syntax_Base.Tm_Bind (({ Pulse_Syntax_Base.binder = b;
                            head = arg;
                            body = (Pulse_Syntax_Naming.close_st_term body v) } : Pulse_Syntax_Base.st_term'__Tm_Bind__payload))) ((x5 : Pulse_Syntax_Base.st_term)).Pulse_Syntax_Base.range)
                      )) x4 x5))))
                  ))
              )))
          )
      ) ps))
  ))

