let rec process_fstar_match_branches (g : Pulse_Typing_Env.env) (rng : FStarC_Range_Type.range) (brs : ((FStarC_Reflection_V2_Data.pattern * FStarC_Reflection_Types.term)) list) (maybe_hoist_fn : (Pulse_Typing_Env.env -> ((FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv) -> (FStarC_Tactics_Types.ref_proofstate -> (Pulse_Typing_Env.env * ((Pulse_Syntax_Base.binder * Prims.int * Pulse_Syntax_Base.st_term)) list * (FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv)))))) : (FStarC_Tactics_Types.ref_proofstate -> (((FStarC_Reflection_V2_Data.pattern * Pulse_Syntax_Base.st_term)) list * bool)) =
  (match brs with
    | [] -> (fun tmp -> ([], false))
    | ((pat, body) :: rest) -> (fun ps -> (let x = (hoist_branch_body g body rng maybe_hoist_fn ps) in
      (match x with
        | (body_st, changed) -> (let x1 = (process_fstar_match_branches g rng rest maybe_hoist_fn ps) in
          (match x1 with
            | (rest_results, rest_changed) -> (((pat, body_st) :: rest_results), (changed || rest_changed))
          ))
      )))
  )

let convert_fstar_match (g : Pulse_Typing_Env.env) (t : FStarC_Reflection_Types.term) (maybe_hoist_fn : (Pulse_Typing_Env.env -> ((FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv) -> (FStarC_Tactics_Types.ref_proofstate -> (Pulse_Typing_Env.env * ((Pulse_Syntax_Base.binder * Prims.int * Pulse_Syntax_Base.st_term)) list * (FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv)))))) : (FStarC_Tactics_Types.ref_proofstate -> (Pulse_Syntax_Base.st_term) option) =
  (let tmp = (FStarC_Reflection_V2_Builtins.inspect_ln t) in
  (match tmp with
    | (FStarC_Reflection_V2_Data.Tv_Match (sc, u__ret, brs)) -> (fun ps -> (let x = (Pulse_RuntimeUtils.range_of_term t) in
      let x1 = (process_fstar_match_branches g x brs maybe_hoist_fn ps) in
      ((match x1 with
        | (results, any_changed) -> (if any_changed then (fun ps1 -> (let x2 = (Pulse_Syntax_Base.mk_term (Pulse_Syntax_Base.Tm_Return (({ Pulse_Syntax_Base.expected_type = Pulse_Syntax_Pure.tm_unknown;
              insert_eq = false;
              term = sc } : Pulse_Syntax_Base.st_term'__Tm_Return__payload))) (Pulse_RuntimeUtils.range_of_term sc)) in
          let x3 = (match results with
              | ((u__pat1, body1) :: ((u__pat2, body2) :: [])) -> (Pulse_Syntax_Base.mk_term (Pulse_Syntax_Base.Tm_If (({ Pulse_Syntax_Base.b = x2;
                  then__ = body1;
                  else__ = body2;
                  pre = None;
                  post = None } : Pulse_Syntax_Base.st_term'__Tm_If__payload))) x)
              | tmp1 -> (let x3 = (FStar_Tactics_Util.map (fun tmp2 -> (match tmp2 with
                    | (rpat, e) -> (match (Pulse_Readback.readback_pat rpat) with
                        | (Some (p)) -> (fun tmp3 -> { Pulse_Syntax_Base.pat = p; e = e; norw = false })
                        | None -> (FStar_Tactics_V2_Derived.fail "Cannot readback pattern from F*-level match during hoisting")
                      )
                  )) results ps1) in
                (Pulse_Syntax_Base.mk_term (Pulse_Syntax_Base.Tm_Match ({ Pulse_Syntax_Base.sc = x2; returns_ = None; brs = x3 })) x))
            ) in
          (Some (x3)))) else (fun tmp1 -> None))
      ) ps)))
    | tmp1 -> (fun tmp2 -> None)
  ))

