let hoist_branch_body (g : Pulse_Typing_Env.env) (body : FStarC_Reflection_Types.term) (rng : FStarC_Range_Type.range) (maybe_hoist_fn : (Pulse_Typing_Env.env -> ((FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv) -> (FStarC_Tactics_Types.ref_proofstate -> (Pulse_Typing_Env.env * ((Pulse_Syntax_Base.binder * Prims.int * Pulse_Syntax_Base.st_term)) list * (FStarC_Syntax_Syntax.term * FStarC_Reflection_V2_Data.aqualv)))))) (ps : FStarC_Tactics_Types.ref_proofstate) : (Pulse_Syntax_Base.st_term * bool) =
