            | (g2, newbs, lifted, kept1, kept2) -> (g2, (FStar_List_Tot_Base.op_At bs newbs), (c :: lifted), kept1, kept2)
          ))
        | None -> (let x2 = (x g ps) in
          (match x2 with
            | (g1, newbs, lifted, kept1, kept2) -> (g1, newbs, lifted, (c1 :: kept1), (c2 :: kept2))
