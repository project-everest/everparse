let rec needs_hoist (p : FStarC_Reflection_Types.term) : (FStarC_Tactics_Types.ref_proofstate -> bool) =
  (match (Pulse_Syntax_Pure.inspect_term p) with
    | (Pulse_Syntax_Pure.Tm_Star (l, r)) -> (fun ps -> (let x = (needs_hoist l ps) in
      (if x then true else ((needs_hoist r) ps))))
    | (Pulse_Syntax_Pure.Tm_ExistsSL (tmp, tmp1, tmp2)) -> (fun tmp3 -> true)
    | (Pulse_Syntax_Pure.Tm_WithPure (tmp, tmp1, tmp2)) -> (fun tmp3 -> true)
    | tmp -> (fun tmp1 -> false)
  )

let rec join_slprop (pick : (bool) option) (linked : bool) (g : Pulse_Typing_Env.env) (b : FStarC_Reflection_Types.term) (ex1 : ((FStarC_Reflection_Types.universe * Pulse_Syntax_Base.binder)) list) (ex2 : ((FStarC_Reflection_Types.universe * Pulse_Syntax_Base.binder)) list) (p1 : FStarC_Reflection_Types.term) (p2 : FStarC_Reflection_Types.term) : (FStarC_Tactics_Types.ref_proofstate -> FStarC_Reflection_Types.term) =
  (match ((Pulse_Syntax_Pure.inspect_term p1), (Pulse_Syntax_Pure.inspect_term p2)) with
    | (Pulse_Syntax_Pure.Tm_IsUnreachable, tmp) -> (fun tmp1 -> p2)
    | (tmp, Pulse_Syntax_Pure.Tm_IsUnreachable) -> (fun tmp1 -> p1)
    | ((Pulse_Syntax_Pure.Tm_WithPure (pred1, n1, p11)), tmp) -> (fun ps -> (let x = (join_slprop pick linked g b ex1 ex1 p11 p2 ps) in
      (guard_with_pure true b pred1 n1 x)))
    | (tmp, (Pulse_Syntax_Pure.Tm_WithPure (pred2, n2, p21))) -> (fun ps -> (let x = (join_slprop pick linked g b ex1 ex1 p1 p21 ps) in
      (guard_with_pure false b pred2 n2 x)))
    | ((Pulse_Syntax_Pure.Tm_ForallSL (tmp, tmp1, tmp2)), tmp3) -> (leftover pick b p1 p2)
    | (tmp, (Pulse_Syntax_Pure.Tm_ForallSL (tmp1, tmp2, tmp3))) -> (leftover pick b p1 p2)
    | ((Pulse_Syntax_Pure.Tm_ExistsSL (tmp, tmp1, tmp2)), tmp3) -> (join_hoisted pick linked g b p1 p2)
    | (tmp, (Pulse_Syntax_Pure.Tm_ExistsSL (tmp1, tmp2, tmp3))) -> (join_hoisted pick linked g b p1 p2)
    | tmp -> (fun ps -> (let x = (needs_hoist p1 ps) in
      let x1 = (if x then true else ((needs_hoist p2) ps)) in
      (if x1 then ((join_hoisted pick linked g b p1 p2) ps) else (let x2 = ((Pulse_Syntax_Pure.slprop_as_list p1), (Pulse_Syntax_Pure.slprop_as_list p2)) in
      (match x2 with
        | (p1s, p2s) -> (let x3 = (partition_matches g p1s p2s ps) in
          (match x3 with
            | (matches, p1s1, p2s1) -> ((Pulse_Checker_Util.debug g "pulse.join_comp" (fun tmp1 -> (fun ps1 -> (let x4 = (Pulse_Show.pulse_Show_show__list_tuple2_term_term matches ps1) in
