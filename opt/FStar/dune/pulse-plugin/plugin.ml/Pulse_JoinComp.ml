let rec salvage_matches (linked : bool) (all1 : (FStarC_Reflection_Types.term) list) (all2 : (FStarC_Reflection_Types.term) list) (g : Pulse_Typing_Env.env) (b : FStarC_Reflection_Types.term) (bs1 : ((FStarC_Reflection_Types.universe * Pulse_Syntax_Base.binder * Prims.int)) list) (bs2 : ((FStarC_Reflection_Types.universe * Pulse_Syntax_Base.binder * Prims.int)) list) (xs1 : (Prims.int) list) (xs2 : (Prims.int) list) (matches : ((FStarC_Reflection_Types.term * FStarC_Reflection_Types.term)) list) : (FStarC_Tactics_Types.ref_proofstate -> (Pulse_Typing_Env.env * ((FStarC_Reflection_Types.universe * Pulse_Syntax_Base.binder * Prims.int)) list * (FStarC_Reflection_Types.term) list * (FStarC_Reflection_Types.term) list * (FStarC_Reflection_Types.term) list)) =
