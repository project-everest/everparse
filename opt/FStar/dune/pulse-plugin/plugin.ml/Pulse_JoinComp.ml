let rec join_comps (g_then : Pulse_Typing_Env.env) (e_then : Pulse_Syntax_Base.st_term) (c_then : Pulse_Syntax_Base.comp) (g_else : Pulse_Typing_Env.env) (e_else : Pulse_Syntax_Base.st_term) (c_else : Pulse_Syntax_Base.comp) (post : Pulse_Typing.post_hint_t) : (FStarC_Tactics_Types.ref_proofstate -> Pulse_Syntax_Base.comp) =
  (fun ps -> (match (c_then, c_else) with
    | ((Pulse_Syntax_Base.C_STAtomic (inames, obs1, st)), (Pulse_Syntax_Base.C_STAtomic (tmp, obs2, tmp1))) -> (Pulse_Syntax_Base.C_STAtomic (inames, (Pulse_Typing.join_obs obs1 obs2), st))
    | ((Pulse_Syntax_Base.C_STGhost (tmp, tmp1)), (Pulse_Syntax_Base.C_STGhost (tmp2, tmp3))) -> c_then
    | ((Pulse_Syntax_Base.C_STDiv (tmp)), (Pulse_Syntax_Base.C_STDiv (tmp1))) -> c_then
    | ((Pulse_Syntax_Base.C_ST (tmp)), (Pulse_Syntax_Base.C_ST (tmp1))) -> c_then
    | tmp -> ((match (c_then, c_else) with
        | ((Pulse_Syntax_Base.C_STGhost (tmp1, tmp2)), (Pulse_Syntax_Base.C_STAtomic (tmp3, tmp4, tmp5))) -> (join_comps g_then e_then (Pulse_Typing_Combinators.st_ghost_as_atomic c_then) g_else e_else c_else post)
        | ((Pulse_Syntax_Base.C_STAtomic (tmp1, tmp2, tmp3)), (Pulse_Syntax_Base.C_STGhost (tmp4, tmp5))) -> (join_comps g_then e_then c_then g_else e_else (Pulse_Typing_Combinators.st_ghost_as_atomic c_else) post)
      ) ps)
  ))

