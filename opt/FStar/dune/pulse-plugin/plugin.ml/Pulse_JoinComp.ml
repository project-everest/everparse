              (match x5 with
                | (pures1, p1s2) -> (let x6 = (guard_pures false b p2s1) in
                  ((match x6 with
                    | (pures2, p2s2) -> (match (p1s2, p2s2) with
                        | ([], []) -> (fun tmp1 -> (Pulse_Syntax_Pure.list_as_slprop (FStar_List_Tot_Base.op_At pures1 (FStar_List_Tot_Base.op_At pures2 x4))))
