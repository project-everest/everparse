      )) else (let x1 = (if (linked && ((shares_hoisted xs1 all1 c1) || (shares_hoisted xs2 all2 c2))) then None else ((generalize_pair g bs1 bs2 xs1 xs2 c1 c2) ps)) in
      (match x1 with
        | (Some ((g1, bs, c))) -> (let x2 = (x g1 ps) in
