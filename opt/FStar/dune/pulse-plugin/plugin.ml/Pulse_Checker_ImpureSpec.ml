    | Pulse_Syntax_Pure.Tm_Emp -> (purify_spec_core g ctxt ts)
    | (Pulse_Syntax_Pure.Tm_WithPure (p, n, body)) -> (fun ps -> (let x = (Pulse_Typing_Env.fresh g) in
