        | tmp -> (fun ps -> (let x = (run_elim g t ps) in
          (match x with
            | (g', xs, t') -> (let x1 = (push_ctxt ctxt t') in
              let x2 = (extrude g' x1 todo1 ts ps) in
              (match x2 with
                | None -> (Some (t))
