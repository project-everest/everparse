and purify_spec_core (g : Pulse_Typing_Env.env) (ctxt : ctxt') (ts : (FStarC_Reflection_Types.term) list) : (FStarC_Tactics_Types.ref_proofstate -> (FStarC_Reflection_Types.term) option) =
  (match ts with
    | [] -> (fun tmp -> None)
    | (t :: ts1) -> (let tmp = (FStarC_Reflection_V2_Builtins.inspect_ln t) in
      (match tmp with
        | (FStarC_Reflection_V2_Data.Tv_Let (false, tmp1, tmp2, def, body)) -> (fun ps -> (let x = (symb_eval_subterms g ctxt def ps) in
          (match x with
            | (tmp3, def1) -> (let x1 = (Pulse_Syntax_Naming.open_term' body def1 Prims.int_zero) in
              (purify_spec_core g ctxt (x1 :: ts1) ps))
          )))
        | (FStarC_Reflection_V2_Data.Tv_Match (sc, ret, ((p, body) :: []))) -> (fun ps -> (let x = (symb_eval_subterms g ctxt sc ps) in
          (match x with
            | (tmp1, sc1) -> (let x1 = (pat_bindings g sc1 p ps) in
              (match x1 with
                | (Some ((g', bs, true))) -> (let x2 = (open_branch_body bs body) in
                  let x3 = (purify_spec_core g' ctxt (x2 :: ts1) ps) in
                  let x4 = (or_emp x3) in
                  let tmp2 = (FStarC_Reflection_V2_Builtins.pack_ln (FStarC_Reflection_V2_Data.Tv_Match (sc1, ret, ((p, (close_branch_body bs x4)) :: [])))) in
                  (Some (tmp2)))
                | tmp2 -> ((purify_spec_default g ctxt t ts1) ps)
              ))
          )))
        | tmp1 -> (purify_spec_default g ctxt t ts1)
      ))
  )

