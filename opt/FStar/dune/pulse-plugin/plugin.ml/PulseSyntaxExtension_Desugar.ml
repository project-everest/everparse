let rec desugar_pat (env : PulseSyntaxExtension_Env.env_t) (p : FStarC_Parser_AST.pattern) : (Prims.int -> (((Pulse_Syntax_Base.pattern * (FStarC_Ident.ident) list), (((PPrint.document) list * FStarC_Range_Type.range)) option) FStar_Pervasives.either * Prims.int)) =
  (let r = (match p with
      | { FStarC_Parser_AST.pat = pat; prange = prange; _ } -> prange
    ) in
  (match (match p with
    | { FStarC_Parser_AST.pat = pat; prange = prange; _ } -> pat
  ) with
    | (FStarC_Parser_AST.PatVar (id, tmp, tmp1)) -> (PulseSyntaxExtension_Err.return ((pat_var (FStarC_Ident.string_of_id id) r), (id :: [])))
    | (FStarC_Parser_AST.PatWild (u__1, u__2)) -> (let id = (FStarC_Ident.mk_ident ("_", r)) in
      (PulseSyntaxExtension_Err.return ((pat_var "_" r), (id :: []))))
    | (FStarC_Parser_AST.PatConst (c)) -> (let c1 = (FStarC_Reflection_V2_Builtins.inspect_const c) in
      (PulseSyntaxExtension_Err.return ((Pulse_Syntax_Base.Pat_Constant (c1)), [])))
    | (FStarC_Parser_AST.PatName (lid)) -> (let tmp = (desugar_datacon env lid) in
      (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp (fun fv -> (let tmp1 = (pat_cons fv [] r) in
      let tmp2 = (tmp1, []) in
      (PulseSyntaxExtension_Err.return tmp2)))))
    | (FStarC_Parser_AST.PatApp ({ FStarC_Parser_AST.pat = (FStarC_Parser_AST.PatName (lid)); prange = tmp; _ }, ({ FStarC_Parser_AST.pat = FStarC_Parser_AST.PatRest; prange = tmp1; _ } :: []))) -> (let tmp2 = (match p with
          | { FStarC_Parser_AST.pat = pat; prange = prange; _ } -> pat
