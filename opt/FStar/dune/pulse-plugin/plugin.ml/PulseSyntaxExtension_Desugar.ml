      (match tmp2 with
        | (FStarC_Parser_AST.PatApp (hd, tmp3)) -> (let tmp4 = (desugar_datacon env lid) in
          (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn_1 tmp4 (fun fv -> (let rest = (FStarC_ToSyntax_ToSyntax.rest_pat_for_lid (env).PulseSyntaxExtension_Env.dsenv lid) in
          let newpat = (FStarC_Parser_AST.mk_pattern (FStarC_Parser_AST.PatApp (hd, rest)) r) in
