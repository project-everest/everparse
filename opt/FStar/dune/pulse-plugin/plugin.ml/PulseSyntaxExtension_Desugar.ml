          (PulseSyntaxExtension_Err.return (pat, (BatList.flatten idents))))
      )))))
    | FStarC_Parser_AST.PatRest -> (PulseSyntaxExtension_Err.fail "Invalid pattern: `..` can only appear applied to a constructor" r)
    | tmp -> (PulseSyntaxExtension_Err.fail "invalid pattern" r)
  ))

