          (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp4 (fun qbs -> (PulseSyntaxExtension_Err.return (slprop_defn range id qbs body1))))))))
      ))))
    | tmp -> (PulseSyntaxExtension_Err.fail "Unexpected Pulse declaration" (PulseSyntaxExtension_Sugar.range_of_decl p))
  )

