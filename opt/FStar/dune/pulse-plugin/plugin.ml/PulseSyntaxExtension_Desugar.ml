              (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp6 (fun comp -> (let tmp7 = (PulseSyntaxExtension_Err.map2 faux bs1 bvs1) in
              (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp7 (fun qbs -> (let tmp8 = (BatList.map (fun b -> (b).Pulse_Syntax_Base.bv_index) (FStar_List_Tot_Base.map (fun tmp8 -> (match tmp8 with
                  | (tmp9, tmp10, bv) -> bv
                )) qbs)) in
              let comp1 = (Pulse_Syntax_Naming.close_comp_n comp tmp8) in
              (PulseSyntaxExtension_Err.return (fn_decl range id us qbs comp1)))))))))
          )))))))
      ))))
    | (PulseSyntaxExtension_Sugar.FnDecl ({ PulseSyntaxExtension_Sugar.id = id; us = us; binders = binders; ascription = (FStar_Pervasives.Inr (ascription)); decorations = tmp; range = range; _ })) -> (PulseSyntaxExtension_Err.fail "Unexpected FnDecl with F* type" range)
    | (PulseSyntaxExtension_Sugar.SlpropDefn ({ PulseSyntaxExtension_Sugar.id = id; binders = binders; body = body; decorations = tmp; range = range; _ })) -> (let tmp1 = (desugar_binders env binders) in
      (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp1 (fun tmp2 -> (match tmp2 with
        | (env1, bs, bvs) -> (let tmp3 = (desugar_term env1 body) in
