          | tmp2 -> (PulseSyntaxExtension_Err.fail "invalid pattern: no deep patterns allowed" r)
        )) args) in
      (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp2 (fun idents -> (let strs = (BatList.map FStarC_Ident.string_of_id idents) in
