    | (PulseSyntaxExtension_Sugar.FnDefn ({ PulseSyntaxExtension_Sugar.id = id; is_rec = true; us = us; binders = binders; ascription = (FStar_Pervasives.Inr (ascription)); measure = None; body = (FStar_Pervasives.Inr (body)); decorations = tmp; range = range; _ })) -> (PulseSyntaxExtension_Err.fail "Recursive Pulse functions cannot be defined as lambdas yet" range)
    | (PulseSyntaxExtension_Sugar.FnDecl ({ PulseSyntaxExtension_Sugar.id = id; us = us; binders = binders; ascription = (FStar_Pervasives.Inl (ascription)); decorations = tmp; range = range; _ })) -> (let tmp1 = (desugar_binders env binders) in
      (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp1 (fun tmp2 -> (match tmp2 with
        | (env1, bs, bvs) -> (let tmp3 = (parse_annots ((ascription : PulseSyntaxExtension_Sugar.computation_type)).PulseSyntaxExtension_Sugar.range (ascription).PulseSyntaxExtension_Sugar.annots) in
          (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp3 (fun pannots -> (let fvs = (PulseSyntaxExtension_Env.free_vars_comp env1 pannots) in
          let tmp4 = (idents_as_binders env1 fvs) in
          (PulseSyntaxExtension_Err.fStarC_Class_Monad_op_let_Bang__fn tmp4 (fun tmp5 -> (match tmp5 with
            | (env2, bs', bvs') -> (let bs1 = (FStar_List_Tot_Base.op_At bs bs') in
