      (match tmp1 with
        | (pats, idents) -> (let tmp2 = (FStarC_Parser_Const_Tuples.mk_tuple_data_lid ((fun l -> Z.of_int (BatList.length l)) pats) r) in
          let ctor = (sw_mk_fv tmp2 r) in
