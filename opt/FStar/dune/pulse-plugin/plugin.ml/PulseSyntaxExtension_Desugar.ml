      ))
    | (FStarC_Parser_AST.PatApp ({ FStarC_Parser_AST.pat = (FStarC_Parser_AST.PatName (lid)); prange = tmp; _ }, args)) -> (let tmp1 = (desugar_datacon env lid) in
