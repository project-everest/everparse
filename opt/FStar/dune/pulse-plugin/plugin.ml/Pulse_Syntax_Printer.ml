    | (Pulse_Syntax_Base.FnDefn ({ Pulse_Syntax_Base.id = id; isrec = isrec; us = tmp; bs = bs; comp = tmp1; meas = tmp2; body = body; _ })) -> (fun ps -> (let x = (FStar_Tactics_Util.map (fun tmp3 -> (match tmp3 with
          | (tmp4, b, tmp5) -> (binder_to_string b)
        )) bs ps) in
      let x1 = (BatString.concat " " x) in
      let x2 = (st_term_to_string body ps) in
      let x3 = (Prims.strcat x2 "}") in
      let x4 = (Prims.strcat " { " x3) in
      let x5 = (Prims.strcat x1 x4) in
      let x6 = (Prims.strcat " " x5) in
      let tmp3 = (FStarC_Reflection_V2_Builtins.inspect_ident id) in
      let tmp4 = (match tmp3 with
          | (u__1, u__2) -> u__1
        ) in
      let x7 = (Prims.strcat tmp4 x6) in
      let x8 = (Prims.strcat (if isrec then "rec " else "") x7) in
      (Prims.strcat "fn " x8)))
    | (Pulse_Syntax_Base.FnDecl ({ Pulse_Syntax_Base.id = id; us = tmp; bs = bs; comp = tmp1; _ })) -> (fun ps -> (let x = (FStar_Tactics_Util.map (fun tmp2 -> (match tmp2 with
          | (tmp3, b, tmp4) -> (binder_to_string b)
        )) bs ps) in
      let x1 = (BatString.concat " " x) in
      let x2 = (Prims.strcat " " x1) in
      let tmp2 = (FStarC_Reflection_V2_Builtins.inspect_ident id) in
      let tmp3 = (match tmp2 with
          | (u__1, u__2) -> u__1
        ) in
      let x3 = (Prims.strcat tmp3 x2) in
      (Prims.strcat "fn " x3)))
    | (Pulse_Syntax_Base.SlpropDefn ({ Pulse_Syntax_Base.id = id; bs = bs; body = body; _ })) -> (fun ps -> (let x = (FStar_Tactics_Util.map (fun tmp -> (match tmp with
          | (tmp1, b, tmp2) -> (binder_to_string b)
        )) bs ps) in
      let x1 = (BatString.concat " " x) in
      let x2 = (term_to_string body ps) in
      let x3 = (Prims.strcat x2 "\n") in
      let x4 = (Prims.strcat " = " x3) in
      let x5 = (Prims.strcat x1 x4) in
      let x6 = (Prims.strcat " " x5) in
      let tmp = (FStarC_Reflection_V2_Builtins.inspect_ident id) in
      let tmp1 = (match tmp with
          | (u__1, u__2) -> u__1
        ) in
      let x7 = (Prims.strcat tmp1 x6) in
      (Prims.strcat "let predicate " x7)))
  )

