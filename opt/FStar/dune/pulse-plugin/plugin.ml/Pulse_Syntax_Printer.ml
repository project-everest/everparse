let effect_annot_to_string (e : Pulse_Syntax_Base.effect_annot) : (FStarC_Tactics_Types.ref_proofstate -> string) =
  (match e with
    | Pulse_Syntax_Base.EffectAnnotSTT -> (fun tmp -> "stt")
    | Pulse_Syntax_Base.EffectAnnotSTTDiv -> (fun tmp -> "stt_div")
    | (Pulse_Syntax_Base.EffectAnnotGhost (opens)) -> (fun ps -> (let x = (term_to_string opens ps) in
      (Prims.strcat "stt_ghost " (Prims.strcat x ""))))
    | (Pulse_Syntax_Base.EffectAnnotAtomic (opens)) -> (fun ps -> (let x = (term_to_string opens ps) in
      (Prims.strcat "stt_atomic " (Prims.strcat x ""))))
    | (Pulse_Syntax_Base.EffectAnnotAtomicOrGhost (opens)) -> (fun ps -> (let x = (term_to_string opens ps) in
      (Prims.strcat "stt_atomic_or_ghost " (Prims.strcat x ""))))
  )

let tag_of_comp (c : Pulse_Syntax_Base.comp) : (FStarC_Tactics_Types.ref_proofstate -> string) =
  (match c with
    | (Pulse_Syntax_Base.C_Tot (tmp)) -> (fun tmp1 -> "Total")
    | (Pulse_Syntax_Base.C_ST (tmp)) -> (fun tmp1 -> "ST")
    | (Pulse_Syntax_Base.C_STDiv (tmp)) -> (fun tmp1 -> "STDiv")
    | (Pulse_Syntax_Base.C_STAtomic (i, obs, tmp)) -> (fun ps -> (let x = (term_to_string i ps) in
      (Prims.strcat (Prims.strcat "" (Prims.strcat (observability_to_string obs) " ")) (Prims.strcat x ""))))
    | (Pulse_Syntax_Base.C_STGhost (tmp, tmp1)) -> (fun tmp2 -> "Ghost")
  )

