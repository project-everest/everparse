let r_freevars_opt (o : ('a) option) (f : ('a -> (Prims.int -> bool))) : (Prims.int -> bool) =
  (match o with
    | None -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (Some (x)) -> (f x)
  )

let rec r_freevars_terms (ts : (FStarC_Reflection_Types.term) list) : (Prims.int -> bool) =
  (match ts with
    | [] -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (t :: ts1) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars t) (r_freevars_terms ts1))
  )

and r_freevars_binder (b : FStarC_Reflection_Types.binder) : (Prims.int -> bool) =
  (let bndr = (FStarC_Reflection_V2_Builtins.inspect_binder b) in
  let tmp = (match bndr with
      | { FStarC_Reflection_V2_Data.sort = sort; qual = qual; attrs = attrs; ppname = ppname; _ } -> sort
    ) in
  let tmp1 = (r_freevars tmp) in
  let tmp2 = (match bndr with
      | { FStarC_Reflection_V2_Data.sort = sort; qual = qual; attrs = attrs; ppname = ppname; _ } -> attrs
    ) in
  let tmp3 = (r_freevars_terms tmp2) in
  (Pulse_FStar_Set.fStar_Set_union tmp1 tmp3))

and r_freevars_flag (f : FStarC_Reflection_V2_Data.cflag) : (Prims.int -> bool) =
  (match f with
    | (FStarC_Reflection_V2_Data.SMTPAT (t)) -> (r_freevars t)
    | (FStarC_Reflection_V2_Data.DECREASES ((FStarC_Reflection_V2_Data.Decreases_lex (ts)))) -> (r_freevars_terms ts)
    | (FStarC_Reflection_V2_Data.DECREASES ((FStarC_Reflection_V2_Data.Decreases_wf (rel, e)))) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars rel) (r_freevars e))
  )

and r_freevars_flags (fs : (FStarC_Reflection_V2_Data.cflag) list) : (Prims.int -> bool) =
  (match fs with
    | [] -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (f :: fs1) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars_flag f) (r_freevars_flags fs1))
  )

and r_freevars_comp (c : FStarC_Reflection_Types.comp) : (Prims.int -> bool) =
  (let cv = (FStarC_Reflection_V2_Builtins.inspect_comp c) in
  let tmp = (match cv with
      | { FStarC_Reflection_V2_Data.effect_name = effect_name; result_typ = result_typ; flags = flags; source_effect_name = source_effect_name; _ } -> result_typ
    ) in
  let tmp1 = (r_freevars tmp) in
  let tmp2 = (match cv with
      | { FStarC_Reflection_V2_Data.effect_name = effect_name; result_typ = result_typ; flags = flags; source_effect_name = source_effect_name; _ } -> flags
    ) in
  let tmp3 = (r_freevars_flags tmp2) in
  (Pulse_FStar_Set.fStar_Set_union tmp1 tmp3))

and r_freevars_match_returns (m : FStarC_Syntax_Syntax.match_returns_ascription) : (Prims.int -> bool) =
  (match m with
    | (b, (ret, as__, eq)) -> (let b1 = (r_freevars_binder b) in
      let ret1 = (match ret with
          | (FStar_Pervasives.Inl (t)) -> (r_freevars t)
          | (FStar_Pervasives.Inr (c)) -> (r_freevars_comp c)
        ) in
      let as_1 = (r_freevars_opt as__ r_freevars) in
      (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union b1 ret1) as_1))
  )

and r_freevars_patterns (ps : ((FStarC_Reflection_V2_Data.pattern * bool)) list) : (Prims.int -> bool) =
  (match ps with
    | [] -> (Pulse_FStar_Set.fStar_Set_empty ())
    | ((p, b) :: ps1) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars_pattern p) (r_freevars_patterns ps1))
  )

and r_freevars_pattern (p : FStarC_Reflection_V2_Data.pattern) : (Prims.int -> bool) =
  (match p with
    | (FStarC_Reflection_V2_Data.Pat_Constant (tmp)) -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (FStarC_Reflection_V2_Data.Pat_Cons (head, univs, subpats)) -> (r_freevars_patterns subpats)
    | (FStarC_Reflection_V2_Data.Pat_Var (bv, s)) -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (FStarC_Reflection_V2_Data.Pat_Dot_Term (topt)) -> (r_freevars_opt topt r_freevars)
  )

and r_freevars_branch (br : (FStarC_Reflection_V2_Data.pattern * FStarC_Syntax_Syntax.term)) : (Prims.int -> bool) =
  (match br with
    | (p, t) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars_pattern p) (r_freevars t))
  )

and r_freevars_branches (brs : ((FStarC_Reflection_V2_Data.pattern * FStarC_Syntax_Syntax.term)) list) : (Prims.int -> bool) =
  (match brs with
    | [] -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (hd :: tl) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars_branch hd) (r_freevars_branches tl))
  )

and r_freevars (e : FStarC_Reflection_Types.term) : (Prims.int -> bool) =
  (let tmp = (FStarC_Reflection_V2_Builtins.inspect_ln e) in
  (match tmp with
    | (FStarC_Reflection_V2_Data.Tv_Uvar (tmp1, tmp2)) -> (Pulse_FStar_Set.fStar_Set_complement (Pulse_FStar_Set.fStar_Set_empty ()))
    | (FStarC_Reflection_V2_Data.Tv_UInst (tmp1, tmp2)) -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (FStarC_Reflection_V2_Data.Tv_FVar (tmp1)) -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (FStarC_Reflection_V2_Data.Tv_Type (tmp1)) -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (FStarC_Reflection_V2_Data.Tv_Const (tmp1)) -> (Pulse_FStar_Set.fStar_Set_empty ())
    | FStarC_Reflection_V2_Data.Tv_Unknown -> (Pulse_FStar_Set.fStar_Set_empty ())
    | FStarC_Reflection_V2_Data.Tv_Unsupp -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (FStarC_Reflection_V2_Data.Tv_BVar (tmp1)) -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (FStarC_Reflection_V2_Data.Tv_Var (x)) -> (Pulse_FStar_Set.fStar_Set_singleton (Pulse_FStar_Reflection_Typing.fStar_Reflection_Typing_namedv_uniq x))
    | (FStarC_Reflection_V2_Data.Tv_App (e1, (e2, tmp1))) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars e1) (r_freevars e2))
    | (FStarC_Reflection_V2_Data.Tv_Abs (b, body)) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars_binder b) (r_freevars body))
    | (FStarC_Reflection_V2_Data.Tv_Arrow (b, c)) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars_binder b) (r_freevars_comp c))
    | (FStarC_Reflection_V2_Data.Tv_Refine (b, f)) -> (Pulse_FStar_Set.fStar_Set_union (r_freevars (Pulse_FStar_Reflection_Typing.fStar_Reflection_Typing_binder_sort b)) (r_freevars f))
    | (FStarC_Reflection_V2_Data.Tv_Let (recf, attrs, b, def, body)) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (r_freevars_terms attrs) (r_freevars (Pulse_FStar_Reflection_Typing.fStar_Reflection_Typing_binder_sort b))) (r_freevars def)) (r_freevars body))
    | (FStarC_Reflection_V2_Data.Tv_Match (scr, ret, brs)) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (r_freevars scr) (r_freevars_opt ret r_freevars_match_returns)) (r_freevars_branches brs))
    | (FStarC_Reflection_V2_Data.Tv_AscribedT (e1, t, tac, b)) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (r_freevars e1) (r_freevars t)) (r_freevars_opt tac r_freevars))
    | (FStarC_Reflection_V2_Data.Tv_AscribedC (e1, c, tac, b)) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (r_freevars e1) (r_freevars_comp c)) (r_freevars_opt tac r_freevars))
  ))

let freevars (t : FStarC_Reflection_Types.term) : (Prims.int -> bool) =
  (r_freevars t)

let rec freevars_list (t : (FStarC_Reflection_Types.term) list) : (Prims.int -> bool) =
  (match t with
    | [] -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (hd :: tl) -> (Pulse_FStar_Set.fStar_Set_union (freevars hd) (freevars_list tl))
  )

let freevars_opt (f : ('u___a -> (Prims.int -> bool))) (x : ('u___a) option) : (Prims.int -> bool) =
  (match x with
    | None -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (Some (x1)) -> (f x1)
  )

let freevars_st_comp (s : Pulse_Syntax_Base.st_comp) : (Prims.int -> bool) =
  (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars (s).Pulse_Syntax_Base.res) (freevars ((s : Pulse_Syntax_Base.st_comp)).Pulse_Syntax_Base.pre)) (freevars ((s : Pulse_Syntax_Base.st_comp)).Pulse_Syntax_Base.post))

let freevars_comp (c : Pulse_Syntax_Base.comp) : (Prims.int -> bool) =
  (match c with
    | (Pulse_Syntax_Base.C_Tot (t)) -> (freevars t)
    | (Pulse_Syntax_Base.C_ST (s)) -> (freevars_st_comp s)
    | (Pulse_Syntax_Base.C_STDiv (s)) -> (freevars_st_comp s)
    | (Pulse_Syntax_Base.C_STGhost (inames, s)) -> (Pulse_FStar_Set.fStar_Set_union (freevars inames) (freevars_st_comp s))
    | (Pulse_Syntax_Base.C_STAtomic (inames, tmp, s)) -> (Pulse_FStar_Set.fStar_Set_union (freevars inames) (freevars_st_comp s))
  )

let freevars_ascription (c : Pulse_Syntax_Base.comp_ascription) : (Prims.int -> bool) =
  (Pulse_FStar_Set.fStar_Set_union (freevars_opt freevars_comp ((c : Pulse_Syntax_Base.comp_ascription)).Pulse_Syntax_Base.elaborated) (freevars_opt freevars_comp (c).Pulse_Syntax_Base.annotated))

let freevars_term_opt (t : (FStarC_Reflection_Types.term) option) : (Prims.int -> bool) =
  (freevars_opt freevars t)

let rec freevars_pairs (pairs : ((FStarC_Reflection_Types.term * FStarC_Reflection_Types.term)) list) : (Prims.int -> bool) =
  (match pairs with
    | [] -> (Pulse_FStar_Set.fStar_Set_empty ())
    | ((t1, t2) :: tl) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars t1) (freevars t2)) (freevars_pairs tl))
  )

let freevars_proof_hint (ht : Pulse_Syntax_Base.proof_hint_type) : (Prims.int -> bool) =
  (match ht with
    | (Pulse_Syntax_Base.ASSERT ({ Pulse_Syntax_Base.p = p; elaborated = tmp; _ })) -> (freevars p)
    | (Pulse_Syntax_Base.FOLD ({ Pulse_Syntax_Base.names = tmp; p = p; _ })) -> (freevars p)
    | (Pulse_Syntax_Base.UNFOLD ({ Pulse_Syntax_Base.names = tmp; p = p; _ })) -> (freevars p)
    | (Pulse_Syntax_Base.RENAME ({ Pulse_Syntax_Base.pairs = pairs; goal = goal; tac_opt = tac_opt; elaborated = tmp; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars_pairs pairs) (freevars_term_opt goal)) (freevars_term_opt tac_opt))
    | (Pulse_Syntax_Base.REWRITE ({ Pulse_Syntax_Base.t1 = t1; t2 = t2; tac_opt = tac_opt; elaborated = tmp; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars t1) (freevars t2)) (freevars_term_opt tac_opt))
    | Pulse_Syntax_Base.WILD -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (Pulse_Syntax_Base.SHOW_PROOF_STATE (tmp)) -> (Pulse_FStar_Set.fStar_Set_empty ())
  )

let rec freevars_terms (t : (Pulse_Syntax_Base.st_term) list) : (Prims.int -> bool) =
  (match t with
    | [] -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (t1 :: ts) -> (Pulse_FStar_Set.fStar_Set_union (freevars_st t1) (freevars_terms ts))
  )

and freevars_branches (t : (Pulse_Syntax_Base.branch) list) : (Prims.int -> bool) =
  (match t with
    | [] -> (Pulse_FStar_Set.fStar_Set_empty ())
    | (b :: tl) -> (Pulse_FStar_Set.fStar_Set_union (freevars_st (b).Pulse_Syntax_Base.e) (freevars_branches tl))
  )

and freevars_st (t : Pulse_Syntax_Base.st_term) : (Prims.int -> bool) =
  (match ((t : Pulse_Syntax_Base.st_term)).Pulse_Syntax_Base.term with
    | (Pulse_Syntax_Base.Tm_Return ({ Pulse_Syntax_Base.expected_type = expected_type; insert_eq = tmp; term = term; _ })) -> (Pulse_FStar_Set.fStar_Set_union (freevars expected_type) (freevars term))
    | (Pulse_Syntax_Base.Tm_Abs ({ Pulse_Syntax_Base.b = b; q = tmp; ascription = ascription; body = body; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars (b).Pulse_Syntax_Base.binder_ty) (freevars_list (b).Pulse_Syntax_Base.binder_attrs)) (freevars_st body)) (freevars_ascription ascription))
    | (Pulse_Syntax_Base.Tm_ST ({ Pulse_Syntax_Base.t = t1; args = args; _ })) -> (Pulse_FStar_Set.fStar_Set_union (freevars t1) (freevars_terms args))
    | (Pulse_Syntax_Base.Tm_Bind ({ Pulse_Syntax_Base.binder = binder; head = head; body = body; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars (binder).Pulse_Syntax_Base.binder_ty) (freevars_list (binder).Pulse_Syntax_Base.binder_attrs)) (freevars_st head)) (freevars_st body))
    | (Pulse_Syntax_Base.Tm_TotBind ({ Pulse_Syntax_Base.binder = binder; head = head; body = body; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars (binder).Pulse_Syntax_Base.binder_ty) (freevars_list (binder).Pulse_Syntax_Base.binder_attrs)) (freevars head)) (freevars_st body))
    | (Pulse_Syntax_Base.Tm_If ({ Pulse_Syntax_Base.b = b; then__ = then__; else__ = else__; pre = pre; post = post; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars_st b) (freevars_st then__)) (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars_st else__) (freevars_term_opt pre)) (freevars_term_opt post)))
    | (Pulse_Syntax_Base.Tm_Match ({ Pulse_Syntax_Base.sc = sc; returns_ = returns_; brs = brs; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars_st sc) (freevars_term_opt returns_)) (freevars_branches brs))
    | (Pulse_Syntax_Base.Tm_IntroPure (p)) -> (freevars p)
    | (Pulse_Syntax_Base.Tm_ElimExists (p)) -> (freevars p)
    | (Pulse_Syntax_Base.Tm_IntroExists ({ Pulse_Syntax_Base.p = p; witnesses = witnesses; _ })) -> (Pulse_FStar_Set.fStar_Set_union (freevars p) (freevars_list witnesses))
    | (Pulse_Syntax_Base.Tm_While ({ Pulse_Syntax_Base.invariant = invariant; loop_requires = loop_requires; meas = meas; condition = condition; body = body; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars invariant) (freevars loop_requires)) (freevars_list meas)) (freevars_st condition)) (freevars_st body))
    | (Pulse_Syntax_Base.Tm_WithLocal ({ Pulse_Syntax_Base.binder = binder; initializer_ = initializer_; body = body; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars (binder).Pulse_Syntax_Base.binder_ty) (freevars_list (binder).Pulse_Syntax_Base.binder_attrs)) (freevars_term_opt initializer_)) (freevars_st body))
    | (Pulse_Syntax_Base.Tm_WithLocalArray ({ Pulse_Syntax_Base.binder = binder; initializer_ = initializer_; length = length; body = body; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars (binder).Pulse_Syntax_Base.binder_ty) (freevars_list (binder).Pulse_Syntax_Base.binder_attrs)) (freevars_term_opt initializer_)) (freevars length)) (freevars_st body))
    | (Pulse_Syntax_Base.Tm_Rewrite ({ Pulse_Syntax_Base.t1 = t1; t2 = t2; tac_opt = tac_opt; elaborated = tmp; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars t1) (freevars t2)) (freevars_term_opt tac_opt))
    | (Pulse_Syntax_Base.Tm_Admit ({ Pulse_Syntax_Base.ctag = tmp; u = tmp1; typ = typ; post = post; _ })) -> (Pulse_FStar_Set.fStar_Set_union (freevars typ) (freevars_term_opt post))
    | (Pulse_Syntax_Base.Tm_Unreachable (c)) -> (freevars_comp c)
    | (Pulse_Syntax_Base.Tm_ProofHintWithBinders ({ Pulse_Syntax_Base.hint_type = hint_type; binders = binders; t = t1; _ })) -> (Pulse_FStar_Set.fStar_Set_union (freevars_proof_hint hint_type) (freevars_st t1))
    | (Pulse_Syntax_Base.Tm_PragmaWithOptions ({ Pulse_Syntax_Base.options = tmp; body = body; _ })) -> (freevars_st body)
    | (Pulse_Syntax_Base.Tm_ForwardJumpLabel ({ Pulse_Syntax_Base.lbl = tmp; body = body; post = post; _ })) -> (Pulse_FStar_Set.fStar_Set_union (freevars_st body) (freevars_comp post))
    | (Pulse_Syntax_Base.Tm_Goto ({ Pulse_Syntax_Base.lbl = lbl; arg = arg; _ })) -> (Pulse_FStar_Set.fStar_Set_union (freevars lbl) (freevars arg))
    | (Pulse_Syntax_Base.Tm_Defer ({ Pulse_Syntax_Base.handler_pre = handler_pre; handler = handler; body = body; _ })) -> (Pulse_FStar_Set.fStar_Set_union (Pulse_FStar_Set.fStar_Set_union (freevars handler_pre) (freevars_st handler)) (freevars_st body))
  )

