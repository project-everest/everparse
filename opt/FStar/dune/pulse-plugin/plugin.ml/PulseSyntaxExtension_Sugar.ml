    | ((If ({ head = h1; requires_slprop = q1; join_slprop = j1; then__ = t1; else_opt = e1; _ })), (If ({ head = h2; requires_slprop = q2; join_slprop = j2; then__ = t2; else_opt = e2; _ }))) -> (let tmp = (eq_stmt h1 h2) in
      let tmp1 = (if tmp then (eq_opt eq_slprop q1 q2) else false) in
      let tmp2 = (if tmp1 then (eq_opt eq_ensures_slprop j1 j2) else false) in
      let tmp3 = (if tmp2 then (eq_stmt t1 t2) else false) in
      (if tmp3 then (eq_opt eq_stmt e1 e2) else false))
    | ((Match ({ head = h1; returns_annot = r1; branches = b1; _ })), (Match ({ head = h2; returns_annot = r2; branches = b2; _ }))) -> (let tmp = (eq_stmt h1 h2) in
      let tmp1 = (if tmp then (eq_opt eq_ensures_slprop r1 r2) else false) in
      (if tmp1 then (forall2 (fun tmp2 tmp3 -> (match (tmp2, tmp3) with
        | ((norw1, p1, s11), (norw2, p2, s21)) -> (let tmp4 = (if ((=) norw1 norw2) then (FStarC_Parser_AST_Diff.eq_pattern p1 p2) else false) in
          (if tmp4 then (eq_stmt s11 s21) else false))
      )) b1 b2) else false))
    | ((While ({ guard = g1; invariant = i1; body = b1; _ })), (While ({ guard = g2; invariant = i2; body = b2; _ }))) -> (let tmp = (eq_stmt g1 g2) in
      let tmp1 = (if tmp then (forall2 eq_while_invariant1 i1 i2) else false) in
      (if tmp1 then (eq_stmt b1 b2) else false))
    | ((Introduce ({ slprop = s11; witnesses = w1; _ })), (Introduce ({ slprop = s21; witnesses = w2; _ }))) -> (let tmp = (eq_slprop s11 s21) in
      (if tmp then (forall2 FStarC_Parser_AST_Diff.eq_term w1 w2) else false))
    | ((Sequence ({ s1 = s11; s2 = s21; _ })), (Sequence ({ s1 = s1'; s2 = s2'; _ }))) -> (let tmp = (eq_stmt s11 s1') in
      (if tmp then (eq_stmt s21 s2') else false))
    | ((ProofHintWithBinders ({ hint_type = ht1; binders = bs1; _ })), (ProofHintWithBinders ({ hint_type = ht2; binders = bs2; _ }))) -> (let tmp = (eq_hint_type ht1 ht2) in
      (if tmp then (forall2 FStarC_Parser_AST_Diff.eq_binder bs1 bs2) else false))
    | ((PragmaSetOptions ({ options = o1; body = b1; _ })), (PragmaSetOptions ({ options = o2; body = b2; _ }))) -> (if ((=) o1 o2) then (eq_stmt b1 b2) else false)
    | ((ForwardJumpLabel ({ body = b1; lbl = l1; post = p1; _ })), (ForwardJumpLabel ({ body = b2; lbl = l2; post = p2; _ }))) -> (let tmp = (eq_stmt b1 b2) in
      let tmp1 = (if tmp then (eq_ident l1 l2) else false) in
      (if tmp1 then (eq_opt eq_ensures_slprop p1 p2) else false))
    | ((Goto ({ lbl = l1; arg = a1; _ })), (Goto ({ lbl = l2; arg = a2; _ }))) -> (let tmp = (eq_ident l1 l2) in
      (if tmp then (eq_opt FStarC_Parser_AST_Diff.eq_term a1 a2) else false))
    | ((Defer ({ handler_pre = p1; defer_handler = h1; _ })), (Defer ({ handler_pre = p2; defer_handler = h2; _ }))) -> (let tmp = (eq_slprop p1 p2) in
      (if tmp then (eq_stmt h1 h2) else false))
    | ((Return (a1)), (Return (a2))) -> (eq_opt FStarC_Parser_AST_Diff.eq_term a1 a2)
    | (Continue, Continue) -> true
    | (Break, Break) -> true
    | tmp -> false
  )

and eq_stmt (s1 : stmt) (s2 : stmt) : bool =
  (eq_stmt' (s1).s (s2).s)

and eq_body (b1 : (stmt, lambda) FStar_Pervasives.either) (b2 : (stmt, lambda) FStar_Pervasives.either) : bool =
  (match (b1, b2) with
    | ((FStar_Pervasives.Inl (s1)), (FStar_Pervasives.Inl (s2))) -> (eq_stmt s1 s2)
    | ((FStar_Pervasives.Inr (l1)), (FStar_Pervasives.Inr (l2))) -> (eq_lambda l1 l2)
    | (tmp, tmp1) -> false
  )

and eq_fn_defn (f1 : fn_defn) (f2 : fn_defn) : bool =
  (let tmp = (eq_ident ((f1 : fn_defn)).id ((f2 : fn_defn)).id) in
  let tmp1 = (if tmp then ((=) (f1).is_rec (f2).is_rec) else false) in
  let tmp2 = (if tmp1 then (forall2 eq_ident ((f1 : fn_defn)).us ((f2 : fn_defn)).us) else false) in
  let tmp3 = (if tmp2 then (forall2 FStarC_Parser_AST_Diff.eq_binder ((f1 : fn_defn)).binders ((f2 : fn_defn)).binders) else false) in
  let tmp4 = (if tmp3 then (eq_ascription ((f1 : fn_defn)).ascription ((f2 : fn_defn)).ascription) else false) in
  let tmp5 = (if tmp4 then (eq_opt FStarC_Parser_AST_Diff.eq_term (f1).measure (f2).measure) else false) in
  (if tmp5 then (eq_body ((f1 : fn_defn)).body ((f2 : fn_defn)).body) else false))

let eq_fn_decl (f1 : fn_decl) (f2 : fn_decl) : bool =
  (let tmp = (eq_ident ((f1 : fn_decl)).id ((f2 : fn_decl)).id) in
  let tmp1 = (if tmp then (forall2 eq_ident ((f1 : fn_decl)).us ((f2 : fn_decl)).us) else false) in
  let tmp2 = (if tmp1 then (forall2 FStarC_Parser_AST_Diff.eq_binder ((f1 : fn_decl)).binders ((f2 : fn_decl)).binders) else false) in
  (if tmp2 then (eq_ascription ((f1 : fn_decl)).ascription ((f2 : fn_decl)).ascription) else false))

let eq_slprop_defn (f1 : slprop_defn) (f2 : slprop_defn) : bool =
  (let tmp = (eq_ident ((f1 : slprop_defn)).id ((f2 : slprop_defn)).id) in
  let tmp1 = (if tmp then (forall2 FStarC_Parser_AST_Diff.eq_binder ((f1 : slprop_defn)).binders ((f2 : slprop_defn)).binders) else false) in
  (if tmp1 then (FStarC_Parser_AST_Diff.eq_term ((f1 : slprop_defn)).body ((f2 : slprop_defn)).body) else false))

let eq_decl (d1 : decl) (d2 : decl) : bool =
  (match (d1, d2) with
    | ((FnDefn (f1)), (FnDefn (f2))) -> (eq_fn_defn f1 f2)
    | ((FnDecl (d11)), (FnDecl (d21))) -> (eq_fn_decl d11 d21)
    | ((SlpropDefn (d11)), (SlpropDefn (d21))) -> (eq_slprop_defn d11 d21)
    | tmp -> false
  )

