  )

and scan_stmt (cbs : FStarC_Parser_AST.dep_scan_callbacks) (s : stmt) : unit =
  (match (s).s with
    | (Open (l)) -> ((match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> add_open
      ) l)
    | (Expr (e)) -> (((match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) (e).e);
      (iter (scan_lambda cbs) (e).args))
    | (ArrayAssignment ({ arr = a; index = i; value = v; _ })) -> (((match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) a);
      ((match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) i);
      ((match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) v))
    | (LetBinding ({ norw = tmp; qualifier = q; pat_attrs = a; pat = p; typ = t; init = init; _ })) -> ((iter (match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) a);
      (scan_let_init cbs init);
      ((match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_pattern
      ) p);
      (iopt (match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) t))
    | (Block (s1)) -> (scan_stmt cbs s1)
    | (If ({ head = h; requires_slprop = q; join_slprop = j; then__ = t; else_opt = e; _ })) -> ((scan_stmt cbs h);
      (iopt (scan_slprop cbs) q);
      (iopt (scan_ensures_slprop cbs) j);
      (scan_stmt cbs t);
      (iopt (scan_stmt cbs) e))
    | (Match ({ head = h; returns_annot = r; branches = b; _ })) -> ((scan_stmt cbs h);
      (iopt (scan_ensures_slprop cbs) r);
      (iter (fun tmp -> (match tmp with
        | (tmp1, p, s1) -> (((match cbs with
            | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_pattern
          ) p);
          (scan_stmt cbs s1))
      )) b))
    | (While ({ guard = g; invariant = i; body = b; _ })) -> ((scan_stmt cbs g);
      (iter (scan_while_invariant1 cbs) i);
      (scan_stmt cbs b))
    | (Introduce ({ slprop = s1; witnesses = w; _ })) -> ((scan_slprop cbs s1);
      (iter (match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) w))
    | (Sequence ({ s1 = s1; s2 = s2; _ })) -> ((scan_stmt cbs s1);
      (scan_stmt cbs s2))
    | (ProofHintWithBinders ({ hint_type = ht; binders = bs; _ })) -> ((scan_hint_type cbs ht);
      (iter (scan_binder cbs) bs))
    | (PragmaSetOptions ({ options = tmp; body = body; _ })) -> (scan_stmt cbs body)
    | (ForwardJumpLabel ({ body = body; lbl = lbl; post = post; _ })) -> ((scan_stmt cbs body);
      (iopt (scan_ensures_slprop cbs) post))
    | (Goto ({ lbl = lbl; arg = arg; _ })) -> (iopt (match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) arg)
    | (Defer ({ handler_pre = handler_pre; defer_handler = defer_handler; _ })) -> ((scan_slprop cbs handler_pre);
      (scan_stmt cbs defer_handler))
    | (Return (arg)) -> (iopt (match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) arg)
    | Continue -> ()
    | Break -> ()
  )

