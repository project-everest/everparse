  )

let scan_hint_type (cbs : FStarC_Parser_AST.dep_scan_callbacks) (h : hint_type) : unit =
  (match h with
    | (ASSERT (s)) -> (scan_slprop cbs s)
    | (ASSUME (s)) -> (scan_slprop cbs s)
    | (UNFOLD (ns, s)) -> (scan_slprop cbs s)
    | (FOLD (ns, s)) -> (scan_slprop cbs s)
    | (RENAME (ts, g, t)) -> ((iter (fun tmp -> (match tmp with
        | (t1, t2) -> (((match cbs with
            | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
          ) t1);
          ((match cbs with
            | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
          ) t2))
      )) ts);
      (iopt (scan_slprop cbs) g);
      (iopt (match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) t))
    | (REWRITE (s1, s2, t)) -> ((scan_slprop cbs s1);
      (scan_slprop cbs s2);
      (iopt (match cbs with
        | { FStarC_Parser_AST.scan_term = scan_term; scan_binder = scan_binder_; scan_pattern = scan_pattern; add_lident = add_lident; add_open = add_open; _ } -> scan_term
      ) t))
    | WILD -> ()
    | (SHOW_PROOF_STATE (tmp)) -> ()
  )

