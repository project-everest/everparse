let rec simplify' (extra : bool) (t0 : FStarC_Reflection_Types.term) (ps : FStarC_Tactics_Types.ref_proofstate) : FStarC_Reflection_Types.term =
  (let x = (thua t0 ps) in
  let x1 = (apply_rules_fix extra x ps) in
  (match (hua x1) with
    | (Some ((h, us, args))) -> (let x2 = (FStar_Tactics_Util.map (fun tmp -> (match tmp with
          | (t, q) -> (fun ps1 -> (let x2 = (simplify' extra t ps1) in
            (x2, q)))
        )) args ps) in
      let x3 = (thua (FStar_Reflection_V2_Derived.mk_app (FStar_Tactics_NamedView.pack (FStar_Tactics_NamedView.Tv_UInst (h, us))) x2) ps) in
      let x4 = (apply_rules_fix extra x3 ps) in
      (match x4 with
        | (u__1, u__2) -> u__1
      ))
    | tmp -> (match x1 with
        | (u__1, u__2) -> u__1
      )
  ))

