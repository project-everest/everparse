and p_stmt_noseq (ps : FStarC_Parser_Pratt.pstate) : PulseSyntaxExtension_Sugar.stmt' =
  (let i0 = (!((match ps with
      | { FStarC_Parser_Pratt.toks = toks; ntoks = ntoks; idx = idx; furthest = furthest; fname = fname; start_pos = start_pos; _ } -> idx
    ))) in
  let tmp = (FStarC_Parser_Pratt.peek_kind ps) in
  (match tmp with
    | FStarC_Parser_TokenKind.OPEN -> ((ignore (FStarC_Parser_Pratt.advance ps));
      let tmp1 = (FStarC_Parser_Grammar.p_quident ps) in
      (PulseSyntaxExtension_Sugar.mk_open tmp1))
    | (FStarC_Parser_TokenKind.KEYWORD ("norewrite")) -> (let norw = (FStarC_Parser_Pratt.accept ps (FStarC_Parser_TokenKind.KEYWORD ("norewrite"))) in
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.LET));
      let tmp1 = (FStarC_Parser_Pratt.accept ps (FStarC_Parser_TokenKind.KEYWORD ("mut"))) in
      let q = (if tmp1 then (Some (PulseSyntaxExtension_Sugar.MUT)) else None) in
      let tmp2 = (p_let_pattern ps) in
      (match tmp2 with
        | (attrs, p) -> (let tmp3 = (FStarC_Parser_Pratt.accept ps FStarC_Parser_TokenKind.COLON) in
          let typ = (if tmp3 then (let tmp4 = (FStarC_Parser_Grammar.app_term_full ps) in
            (Some (tmp4))) else None) in
          let init = (p_let_init ps) in
          (PulseSyntaxExtension_Sugar.mk_let_binding norw q attrs p typ init))
      ))
    | FStarC_Parser_TokenKind.LET -> (let norw = (FStarC_Parser_Pratt.accept ps (FStarC_Parser_TokenKind.KEYWORD ("norewrite"))) in
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.LET));
      let tmp1 = (FStarC_Parser_Pratt.accept ps (FStarC_Parser_TokenKind.KEYWORD ("mut"))) in
      let q = (if tmp1 then (Some (PulseSyntaxExtension_Sugar.MUT)) else None) in
      let tmp2 = (p_let_pattern ps) in
      (match tmp2 with
        | (attrs, p) -> (let tmp3 = (FStarC_Parser_Pratt.accept ps FStarC_Parser_TokenKind.COLON) in
          let typ = (if tmp3 then (let tmp4 = (FStarC_Parser_Grammar.app_term_full ps) in
            (Some (tmp4))) else None) in
          let init = (p_let_init ps) in
          (PulseSyntaxExtension_Sugar.mk_let_binding norw q attrs p typ init))
      ))
    | FStarC_Parser_TokenKind.IF -> (p_if ps)
    | (FStarC_Parser_TokenKind.KEYWORD ("while")) -> ((ignore (FStarC_Parser_Pratt.advance ps));
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.LPAREN));
      let tm = (p_stmt ps) in
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.RPAREN));
      let inv = (p_while_invariant ps) in
      let body = (p_braced_stmt ps) in
      (PulseSyntaxExtension_Sugar.mk_while tm inv body))
    | FStarC_Parser_TokenKind.INTRO -> ((ignore (FStarC_Parser_Pratt.advance ps));
      let p = (p_slprop ps) in
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.WITH));
      let tmp1 = ((p_stmt_noseq__ws ps) ()) in
      (PulseSyntaxExtension_Sugar.mk_intro p tmp1))
    | FStarC_Parser_TokenKind.WITH -> (let bs = (with_binders ps) in
      (proof_hint ps bs))
    | (FStarC_Parser_TokenKind.KEYWORD ("rewrite")) -> (proof_hint ps [])
    | FStarC_Parser_TokenKind.ASSERT -> (proof_hint ps [])
    | FStarC_Parser_TokenKind.ASSUME -> (proof_hint ps [])
    | FStarC_Parser_TokenKind.UNFOLD -> (proof_hint ps [])
    | (FStarC_Parser_TokenKind.KEYWORD ("fold")) -> (proof_hint ps [])
    | (FStarC_Parser_TokenKind.KEYWORD ("show_proof_state")) -> (let t = (FStarC_Parser_Pratt.advance ps) in
      (PulseSyntaxExtension_Sugar.mk_proof_hint_with_binders (PulseSyntaxExtension_Sugar.SHOW_PROOF_STATE ((FStarC_Parser_Pratt.tok_rng ps t))) []))
    | FStarC_Parser_TokenKind.CALC -> (let tmp1 = (FStarC_Parser_Grammar.r_calc ps FStarC_Parser_Grammar.dflt) in
      (PulseSyntaxExtension_Sugar.mk_expr tmp1 []))
    | FStarC_Parser_TokenKind.LBRACE -> (let body = (p_braced_stmt ps) in
      let tmp1 = (is_ensures_start ps) in
      let tmp2 = (if tmp1 then true else (FStarC_Parser_Pratt.is ps (FStarC_Parser_TokenKind.KEYWORD ("label")))) in
      (if tmp2 then (let post = (opt_ensures_slprop ps) in
      (ignore (FStarC_Parser_Pratt.expect ps (FStarC_Parser_TokenKind.KEYWORD ("label"))));
      let lbl = (FStarC_Parser_Grammar.p_lident ps) in
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.COLON));
      (PulseSyntaxExtension_Sugar.mk_forward_jump_label body lbl post)) else (PulseSyntaxExtension_Sugar.mk_block body)))
    | (FStarC_Parser_TokenKind.KEYWORD ("label")) -> ((ignore (FStarC_Parser_Pratt.advance ps));
      let lbl = (FStarC_Parser_Grammar.p_lident ps) in
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.COLON));
      let body = (p_braced_stmt ps) in
      let post = (opt_ensures_slprop ps) in
      (PulseSyntaxExtension_Sugar.mk_forward_jump_label body lbl post))
    | FStarC_Parser_TokenKind.MATCH -> ((ignore (FStarC_Parser_Pratt.advance ps));
      let i_t = (!((match ps with
          | { FStarC_Parser_Pratt.toks = toks; ntoks = ntoks; idx = idx; furthest = furthest; fname = fname; start_pos = start_pos; _ } -> idx
        ))) in
      let tm = (p_appTermNoRecordExp ps) in
      let tmp1 = (FStarC_Parser_Pratt.loc ps i_t) in
      let head = (PulseSyntaxExtension_Sugar.mk_stmt (PulseSyntaxExtension_Sugar.mk_expr tm []) tmp1) in
      let c = (opt_ensures_slprop ps) in
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.LBRACE));
      let brs = ((p_stmt_noseq__brs ps) ()) in
      (ignore (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.RBRACE));
      (PulseSyntaxExtension_Sugar.mk_match head c brs))
    | FStarC_Parser_TokenKind.PRAGMA_SET_OPTIONS -> ((ignore (FStarC_Parser_Pratt.advance ps));
      let tmp1 = (FStarC_Parser_Pratt.expect ps FStarC_Parser_TokenKind.STRING) in
      let options = (match tmp1 with
          | { FStarC_Parser_Lexer.kind = kind; text = text; sp = sp; ep = ep; extra = extra; ncom = ncom; _ } -> text
        ) in
      let s = (p_braced_stmt ps) in
      (PulseSyntaxExtension_Sugar.mk_pragma_set_options options s))
    | (FStarC_Parser_TokenKind.KEYWORD ("goto")) -> ((ignore (FStarC_Parser_Pratt.advance ps));
      let lbl = (FStarC_Parser_Grammar.p_lident ps) in
      let tmp1 = (opt_noSeqTerm ps) in
      (PulseSyntaxExtension_Sugar.mk_goto lbl tmp1))
    | (FStarC_Parser_TokenKind.KEYWORD ("defer")) -> ((ignore (FStarC_Parser_Pratt.advance ps));
      let pre = (p_appTermNoRecordExp ps) in
      let h = (p_braced_stmt ps) in
      (PulseSyntaxExtension_Sugar.mk_defer pre h))
    | (FStarC_Parser_TokenKind.KEYWORD ("return")) -> ((ignore (FStarC_Parser_Pratt.advance ps));
      let tmp1 = (opt_noSeqTerm ps) in
      (PulseSyntaxExtension_Sugar.mk_return tmp1))
    | (FStarC_Parser_TokenKind.KEYWORD ("continue")) -> ((ignore (FStarC_Parser_Pratt.advance ps));
      PulseSyntaxExtension_Sugar.mk_continue)
    | (FStarC_Parser_TokenKind.KEYWORD ("break")) -> ((ignore (FStarC_Parser_Pratt.advance ps));
      PulseSyntaxExtension_Sugar.mk_break)
    | k -> (let tmp1 = (if ((=) k (FStarC_Parser_TokenKind.KEYWORD ("fn"))) then true else (if (is_qual_kind k) then (let tmp1 = (FStarC_Parser_Pratt.peek_kind_n ps Prims.int_one) in
