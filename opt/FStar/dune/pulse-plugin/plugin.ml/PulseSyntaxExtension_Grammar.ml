let proof_hint (ps : FStarC_Parser_Pratt.pstate) (bs : (FStarC_Parser_AST.binder) list) : PulseSyntaxExtension_Sugar.stmt' =
  (let tmp = (FStarC_Parser_Pratt.advance ps) in
  let tmp1 = (match tmp with
      | { FStarC_Parser_Lexer.kind = kind; text = text; sp = sp; ep = ep; extra = extra; ncom = ncom; _ } -> kind
    ) in
  let ht = (match tmp1 with
      | (FStarC_Parser_TokenKind.KEYWORD ("rewrite")) -> (rewrite_body ps)
      | FStarC_Parser_TokenKind.ASSERT -> (let tmp2 = (p_slprop ps) in
        (PulseSyntaxExtension_Sugar.ASSERT (tmp2)))
      | FStarC_Parser_TokenKind.ASSUME -> (let tmp2 = (p_slprop ps) in
        (PulseSyntaxExtension_Sugar.ASSUME (tmp2)))
      | FStarC_Parser_TokenKind.UNFOLD -> (let ns = (optional_names ps) in
        let tmp2 = (p_slprop ps) in
        let tmp3 = (ns, tmp2) in
        (PulseSyntaxExtension_Sugar.UNFOLD ((match tmp3 with (custard_tup, _) -> custard_tup), (match tmp3 with (_, custard_tup) -> custard_tup))))
      | (FStarC_Parser_TokenKind.KEYWORD ("fold")) -> (let ns = (optional_names ps) in
        let tmp2 = (p_slprop ps) in
        let tmp3 = (ns, tmp2) in
        (PulseSyntaxExtension_Sugar.FOLD ((match tmp3 with (custard_tup, _) -> custard_tup), (match tmp3 with (_, custard_tup) -> custard_tup))))
      | FStarC_Parser_TokenKind.UNDERSCORE -> (if (match bs with
          | [] -> true
          | tmp2 -> false
        ) then ((Pulse_FStarC_Parser_Pratt.fStarC_Parser_Pratt_backup ps Prims.int_one);
        (FStarC_Parser_Pratt.fail ps)) else PulseSyntaxExtension_Sugar.WILD)
      | tmp2 -> ((Pulse_FStarC_Parser_Pratt.fStarC_Parser_Pratt_backup ps Prims.int_one);
        (FStarC_Parser_Pratt.fail ps))
    ) in
  (PulseSyntaxExtension_Sugar.mk_proof_hint_with_binders ht bs))

