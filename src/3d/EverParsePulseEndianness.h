/* Endianness support for code generated by `3d --pulse`.

   Under `--pulse` the probe copy buffer is a concrete struct
   (`EVERPARSE_COPY_BUFFER_T`) emitted by KaRaMeL into `EverParse.h`, rather
   than the opaque `void*` of the Low* backend. Defining the guard below before
   including `EverParseEndianness.h` suppresses the legacy typedef, so that the
   two definitions do not clash. */

#ifndef EverParsePulseEndianness_H
#define EverParsePulseEndianness_H

#define EVERPARSE_COPY_BUFFER_T_DEFINED

#include "EverParseEndianness.h"

#endif
